// ===== Funções auxiliares =====

const meses = ['jan', 'fev', 'mar', 'abr', 'mai', 'jun', 'jul', 'ago', 'set', 'out', 'nov', 'dez']

// "01/02/2023" vira "fev 2023"
function formatarData(data) {
    if (!data) return ''
    const partes = data.split('/')
    if (partes.length === 3) return meses[Number(partes[1]) - 1] + ' ' + partes[2]
    return data
}

// Monta "fev 2023 – nov 2025" (ou "fev 2023 – Atual")
function periodo(inicio, fim, atual) {
    return [formatarData(inicio), atual ? 'Atual' : formatarData(fim)].filter(Boolean).join(' – ')
}

// Preenche uma lista de chips (<ul class="chips">) recebendo o elemento
function preencherChips(ul, lista) {
    ul.replaceChildren()
    for (const texto of lista) {
        const li = document.createElement('li')
        li.textContent = texto
        ul.append(li)
    }
}

// Preenche uma lista de tópicos (<ul class="bullets">)
function preencherTopicos(ul, lista) {
    ul.replaceChildren()
    for (const texto of lista) {
        const li = document.createElement('li')
        li.textContent = texto
        ul.append(li)
    }
}

